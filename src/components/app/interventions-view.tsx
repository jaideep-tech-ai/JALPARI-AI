'use client';

import { useCallback, useEffect, useState } from 'react';
import { useTranslations } from 'next-intl';
import { api, timeAgo, formatINR } from '@/lib/client-api';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Card, CardContent } from '@/components/ui/card';
import { Skeleton } from '@/components/ui/skeleton';
import { PriorityBadge, SeverityBadge, StatusPill, DemoBanner } from '@/components/shared/widgets';
import { TaskDetailDialog, TaskCreateDialog, type Task } from './tasks-view';
import { toast } from '@/hooks/use-toast';
import { useAppStore } from '@/lib/store';
import type { RiskFactor, Severity } from '@/lib/types';
import { Lightbulb, MapPin, Users, IndianRupee, ShieldCheck, CheckCircle2, XCircle, Info, ArrowRightLeft, Loader2 } from 'lucide-react';

interface Rec {
  id: string;
  title: string;
  actionType: string;
  rationale: string;
  priority: string;
  resources: string | null;
  estCostInr: number | null;
  benefit: string | null;
  verificationMethod: string | null;
  status: string;
  isDemo: boolean;
  createdAt: string;
  asset?: { name: string; code: string; city: string; lat: number; lon: number } | null;
  assessment?: { score: number; severity: string; factors: string; confidence: number; source: string } | null;
}

export function InterventionsView() {
  const t = useTranslations('app.interventions');
  const tType = useTranslations('app.taskType');
  const tStatus = useTranslations('app.status');
  const tSev = useTranslations('app.severity');
  const { user } = useAppStore();
  const [recs, setRecs] = useState<Rec[]>([]);
  const [loading, setLoading] = useState(true);
  const [statusFilter, setStatusFilter] = useState('PENDING');
  const [busyId, setBusyId] = useState<string | null>(null);
  const [createdTask, setCreatedTask] = useState<Task | null>(null);
  const [showAll, setShowAll] = useState(false);

  const isOp = ['municipal', 'disaster', 'super_admin'].includes(user?.role ?? '');

  const refresh = useCallback(async () => {
    setLoading(true);
    try {
      const r = await api<{ recommendations: Rec[] }>('/api/recommendations');
      setRecs(r.recommendations);
    } catch {
      setRecs([]);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => { refresh(); }, [refresh]);

  async function decide(id: string, decision: 'accept' | 'reject') {
    setBusyId(id);
    try {
      const res = await api<{ status: string; taskId?: string }>('/api/recommendations', {
        method: 'PATCH',
        body: { id, decision },
      });
      toast({ title: decision === 'accept' ? t('accepted') : t('rejected') });
      await refresh();
      if (res.taskId) {
        const r2 = await api<{ tasks: Task[] }>('/api/tasks');
        const tk = r2.tasks.find((x) => x.id === res.taskId);
        if (tk) setCreatedTask(tk);
      }
    } catch (e) {
      toast({ title: (e as Error).message, variant: 'destructive' });
    } finally {
      setBusyId(null);
    }
  }

  const filtered = recs.filter((r) => showAll || r.status === statusFilter);
  const pendingCount = recs.filter((r) => r.status === 'PENDING').length;

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <h1 className="text-lg font-bold">{t('title')}</h1>
          <p className="text-[12.5px] text-muted-foreground">{pendingCount} pending decision{pendingCount === 1 ? '' : 's'}</p>
        </div>
        <div className="flex gap-2">
          {['PENDING', 'CONVERTED', 'REJECTED', 'ALL'].map((s) => (
            <Button key={s} size="sm" variant={s === 'ALL' ? showAll : !showAll && statusFilter === s ? 'secondary' : 'ghost'} className="h-8 text-xs" onClick={() => { if (s === 'ALL') setShowAll(true); else { setShowAll(false); setStatusFilter(s); } }}>
              {s === 'ALL' ? 'All' : tStatus(s as 'PENDING')}
            </Button>
          ))}
        </div>
      </div>

      <DemoBanner>
        Recommendations are generated by the transparent rule engine (v0.9) over demo assets and weather signals. {t('humanNote')}
      </DemoBanner>

      {loading ? (
        <div className="grid gap-3 lg:grid-cols-2">{[1, 2, 3, 4].map((i) => <Skeleton key={i} className="h-52 rounded-xl" />)}</div>
      ) : filtered.length === 0 ? (
        <Card>
          <CardContent className="flex flex-col items-center gap-2 py-12 text-center">
            <Lightbulb className="size-8 text-muted-foreground/50" />
            <p className="text-sm text-muted-foreground">No recommendations in this view. Generate assessments from the dashboard to create new ones.</p>
          </CardContent>
        </Card>
      ) : (
        <div className="grid gap-3 lg:grid-cols-2">
          {filtered.map((r) => {
            const factors: RiskFactor[] = (() => {
              try { return JSON.parse(r.assessment?.factors ?? '[]'); } catch { return []; }
            })();
            return (
              <Card key={r.id} className="jg-card-hover flex h-full flex-col py-4">
                <CardContent className="flex flex-1 flex-col gap-3 px-4">
                  <div className="flex items-start justify-between gap-2">
                    <div className="min-w-0">
                      <div className="text-[14px] font-bold leading-snug">{r.title}</div>
                      <div className="mt-1 flex flex-wrap items-center gap-1.5 text-[11px] text-muted-foreground">
                        <Badge variant="outline" className="text-[9px]">{tType(r.actionType as 'DRAIN_INSPECTION')}</Badge>
                        {r.asset && <span className="inline-flex items-center gap-1"><MapPin className="size-3" />{r.asset.name} · {r.asset.city}</span>}
                      </div>
                    </div>
                    <div className="flex shrink-0 flex-col items-end gap-1">
                      <PriorityBadge priority={r.priority as 'MEDIUM'} />
                      <StatusPill status={r.status} />
                    </div>
                  </div>

                  {r.assessment && (
                    <div className="rounded-lg border bg-muted/30 px-3 py-2">
                      <div className="flex items-center justify-between">
                        <span className="text-[10px] font-bold uppercase tracking-widest text-muted-foreground">{t('fromAssessment')}</span>
                        <SeverityBadge severity={r.assessment.severity as Severity} score={r.assessment.score} />
                      </div>
                      <div className="mt-1.5 flex flex-wrap gap-1.5">
                        {factors.filter((f) => f.weight > 0).slice(0, 3).map((f) => (
                          <span key={f.key} className="rounded bg-accent px-1.5 py-0.5 text-[10px] font-medium text-accent-foreground">
                            {f.label} +{f.weight}
                          </span>
                        ))}
                      </div>
                    </div>
                  )}

                  <div className="space-y-1.5 text-[12.5px] leading-relaxed">
                    <div><span className="font-semibold">{t('why')}:</span> <span className="text-muted-foreground">{r.rationale}</span></div>
                    <div className="grid grid-cols-2 gap-x-4 gap-y-1 text-[12px] text-muted-foreground">
                      <span className="flex items-center gap-1"><Users className="size-3" /> {r.resources ?? '—'}</span>
                      <span className="flex items-center gap-1"><IndianRupee className="size-3" /> {formatINR(r.estCostInr)}</span>
                    </div>
                    {r.benefit && <div className="text-[12px] text-muted-foreground"><span className="font-semibold text-foreground">{t('benefit')}:</span> {r.benefit}</div>}
                    {r.verificationMethod && (
                      <div className="flex items-start gap-1.5 text-[12px] text-muted-foreground">
                        <ShieldCheck className="mt-0.5 size-3.5 shrink-0 text-emerald-500" />
                        <span><span className="font-semibold text-foreground">{t('verification')}:</span> {r.verificationMethod}</span>
                      </div>
                    )}
                  </div>

                  <div className="mt-auto flex items-center justify-between gap-2 border-t pt-2.5">
                    <span className="text-[10px] text-muted-foreground">{timeAgo(r.createdAt)}{r.isDemo ? ' · DEMO' : ''}</span>
                    {r.status === 'PENDING' && isOp && (
                      <div className="flex gap-1.5">
                        <Button size="sm" className="h-7 bg-emerald-500 text-[11px] font-semibold text-[#06251B] hover:bg-emerald-400" disabled={busyId === r.id} onClick={() => decide(r.id, 'accept')}>
                          {busyId === r.id ? <Loader2 className="size-3 animate-spin" /> : <CheckCircle2 className="size-3.5" />}
                          {t('accept')}
                        </Button>
                        <Button size="sm" variant="outline" className="h-7 border-red-500/40 text-[11px] text-red-500" disabled={busyId === r.id} onClick={() => decide(r.id, 'reject')}>
                          <XCircle className="size-3.5" /> {t('reject')}
                        </Button>
                      </div>
                    )}
                    {r.status === 'PENDING' && !isOp && (
                      <span className="inline-flex items-center gap-1 text-[10.5px] text-muted-foreground"><Info className="size-3" /> Officer decision required</span>
                    )}
                    {r.status === 'CONVERTED' && (
                      <span className="inline-flex items-center gap-1 text-[11px] font-medium text-teal-500"><ArrowRightLeft className="size-3" /> {tStatus('CONVERTED')}</span>
                    )}
                  </div>
                </CardContent>
              </Card>
            );
          })}
        </div>
      )}

      <TaskDetailDialog task={createdTask} onClose={() => setCreatedTask(null)} onChanged={refresh} />
      <TaskCreateDialog open={false} onClose={() => {}} />
    </div>
  );
}
